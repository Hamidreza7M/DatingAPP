package ir.fastlove.app.core.domain

import ir.fastlove.app.core.model.ChatMessage
import ir.fastlove.app.core.model.MsgType
import ir.fastlove.app.core.model.Person

/**
 * Rule-based, topic-aware demo chat replies. No network/LLM — fully deterministic given the
 * conversation so far, so the chat feels alive while staying a clear, local simulation.
 */
object DemoReply {

    private val shortFollowUps = setOf(
        "آره", "اره", "بله", "نه", "دقیقاً", "دقیقا", "موافقم",
        "منم همینطور", "منم", "درسته", "چه خوب", "جالبه", "مرسی", "ممنون"
    )

    fun topicOf(text: String): String {
        val m = text.trim().lowercase()
        return when {
            listOf("سلام", "درود", "خوبی", "چطوری", "چه خبر").any { it in m } -> "greeting"
            listOf("موسیقی", "آهنگ", "اسپاتیفای", "spotify", "خواننده", "کنسرت").any { it in m } -> "music"
            listOf("سفر", "مسافرت", "گردش", "شهر", "مسیر", "تعطیلات").any { it in m } -> "travel"
            listOf("کافه", "قهوه", "کافی", "رستوران", "غذا").any { it in m } -> "cafe"
            listOf("کتاب", "مطالعه", "رمان", "داستان").any { it in m } -> "book"
            listOf("فیلم", "سریال", "سینما", "بازیگر").any { it in m } -> "movie"
            listOf("کار", "شغل", "درس", "دانشگاه", "شرکت", "حرفه").any { it in m } -> "work"
            listOf("ورزش", "باشگاه", "فوتبال", "یوگا", "پیاده", "دویدن").any { it in m } -> "sport"
            listOf("خودت", "تو چی", "تو چطور", "از خودت", "علاقه‌ات").any { it in m } -> "about_person"
            else -> "general"
        }
    }

    fun reply(userText: String, person: Person, conversation: List<ChatMessage>): String {
        val message = userText.trim()
        val normalized = message.lowercase()
        val isShortFollowUp = normalized in shortFollowUps
        val previousUserText = conversation.dropLast(1).lastOrNull {
            it.isMe && it.type == MsgType.TEXT && it.text.trim().lowercase() !in shortFollowUps
        }?.text
        val topic = if (isShortFollowUp && previousUserText != null) topicOf(previousUserText) else topicOf(message)
        val hasOpeningGreeting = conversation.firstOrNull()?.let {
            !it.isMe && it.type == MsgType.TEXT && it.text.startsWith("سلام! خوشحالم")
        } == true
        val replyTurn = (conversation.count { !it.isMe && it.type == MsgType.TEXT } - if (hasOpeningGreeting) 1 else 0)
            .coerceAtLeast(0)
        val otherInterest = person.interests.firstOrNull() ?: "گفت‌وگوهای خوب"
        val secondInterest = person.interests.getOrNull(1) ?: "موسیقی"
        val city = person.city.ifBlank { "شهر خودم" }
        val clipped = message.take(70) + if (message.length > 70) "…" else ""

        val replies = when (topic) {
            "greeting" -> listOf(
                "سلام، چه خوب که پیام دادی 😊 روزت تا اینجا چطور گذشته؟",
                "مرسی، خوبم! خوشحالم داریم بیشتر آشنا می‌شیم. وقت آزاد که داری دوست داری چیکار کنی؟",
                "سلام دوباره 😊 امروز روز شلوغی داشتی یا برای خودت وقت گذاشتی؟",
                "خوشحالم که گپ می‌زنیم. این روزها چیزی هست که منتظرش باشی؟",
                "راستی آخر هفته‌ات رو معمولاً چطور می‌گذرونی؛ استراحت یا بیرون رفتن؟"
            )
            "music" -> listOf(
                "من معمولاً سراغ $otherInterest و آهنگ‌های آروم می‌رم 🎧 تو با آهنگ انرژی می‌گیری یا ملایم؟",
                "چه انتخاب خوبی! اخیراً آهنگی بوده که چند بار پشت سر هم گوشش بدی؟",
                "من پلی‌لیست‌های متنوع رو دوست دارم. برای پیاده‌روی چه آهنگی پیشنهاد می‌کنی؟",
                "اگه بخوای فقط یک خواننده رو برای یک سفر طولانی انتخاب کنی، کیه؟",
                "آهنگ‌ها رو بر اساس حالت انتخاب می‌کنی یا سبک خاصی رو دنبال می‌کنی؟"
            )
            "travel" -> listOf(
                "سفر همیشه حال آدم رو عوض می‌کنه ✈️ تو سفر برنامه‌ریزی‌شده رو ترجیح می‌دی یا یهویی؟",
                "بین شلوغی و طبیعت خلوت، من طبیعت رو انتخاب می‌کنم. بهترین خاطره سفرت چی بوده؟",
                "اگه همین آخر هفته فرصت سفر کوتاه داشته باشی، کجا رو انتخاب می‌کنی؟",
                "من از کشف جاهای کمترشناخته‌شده‌ی $city لذت می‌برم. تو جاذبه‌های معروف رو می‌بینی یا محلی؟",
                "سفر با دوست‌ها رو بیشتر دوست داری یا یک سفر آروم و دونفره؟"
            )
            "cafe" -> listOf(
                "من کافه‌های دنج با موسیقی ملایم رو دوست دارم ☕ تو فضای خلوت رو می‌پسندی یا پرجنب‌وجوش؟",
                "یک قهوه خوب و گفت‌وگوی طولانی ترکیب جذابیه! نوشیدنی همیشگی‌ات چیه؟",
                "پس باید یک روز چند کافه خوب رو امتحان کنیم 😊 کافه با منظره یا فضای جمع‌وجور؟",
                "اگه یک کافه رو چند بار انتخاب کنی، به قهوه‌اش اهمیت می‌دی یا فضاش؟",
                "من کنار قهوه یک دسر کوچیک هم می‌گیرم 😄 شیرینی دوست داری یا خوراکی شور؟"
            )
            "book" -> listOf(
                "کتاب خوب آدم رو چند روز درگیر می‌کنه 📚 بیشتر رمان می‌خونی یا غیرداستانی؟",
                "من داستان‌هایی رو دوست دارم که شخصیت‌هاشون باورپذیر باشن. کتابی هست دوباره بخونیش؟",
                "این رو باید به فهرست مطالعه‌ام اضافه کنم. آخرین چیزی که خوندی چی بود؟",
                "برای کتاب خوندن سکوت رو ترجیح می‌دی یا موسیقی بی‌کلام؟",
                "شخصیت کتابی‌ای هست که بعد از تموم‌شدن داستان یادت مونده باشه؟"
            )
            "movie" -> listOf(
                "فیلم خوب با همراه خوش‌سلیقه می‌چسبه 🎬 پایان‌های غیرقابل‌پیش‌بینی یا داستان آروم؟",
                "من فیلمی رو انتخاب می‌کنم که بعدش بشه درباره‌اش حرف زد. آخرین فیلم خوبت چی بود؟",
                "اگه امشب فیلم ببینیم، انتخابت کمدیه یا معمایی؟",
                "سریال کوتاه رو ترجیح می‌دی یا داستانی چندفصلی؟",
                "فیلمی هست که هر بار ببینیش باز هم جذاب باشه؟"
            )
            "work" -> listOf(
                "به نظر میاد برات مهمه کارت معنا داشته باشه. کدوم بخشش بیشتر انرژی می‌ده؟",
                "مسیر رسیدن به این حوزه چطور بود؟ از اول علاقه داشتی یا کم‌کم انتخابش کردی؟",
                "بیرون از کار چی کمک می‌کنه ذهنت رو جدا کنی؟",
                "اگه می‌تونستی یک مهارت تازه یاد بگیری، چی انتخاب می‌کردی؟",
                "تعادل کار و زندگی برات آسونه یا هنوز داری راهش رو پیدا می‌کنی؟"
            )
            "sport" -> listOf(
                "چه خوب! من هم تحرک رو دوست دارم 💪 ورزش انفرادی رو می‌پسندی یا گروهی؟",
                "ثبات توی ورزش از خود تمرین سخت‌تره! چی انگیزه‌ات رو حفظ می‌کنه؟",
                "اگه یک فعالیت تازه امتحان کنی، چی رو انتخاب می‌کنی؟",
                "صبح‌ها ورزش می‌کنی یا عصرها؟ فکر کنم زمانش روی انگیزه اثر داره.",
                "ورزشی هست که دلت خواسته امتحانش کنی ولی فرصت نشده؟"
            )
            "about_person" -> listOf(
                "من به $otherInterest علاقه دارم و از تجربه‌های تازه خوشم میاد 😊 $secondInterest هم جزو برنامه‌هامه. تو چی رو خسته‌کننده نمی‌دونی؟",
                "از گفت‌وگوی صمیمی و آدم‌های کنجکاو خوشم میاد. چی بیشتر از همه خوشحالت می‌کنه؟",
                "من بیشتر اهل تجربه‌کردنم تا برنامه‌ریزی. تو اهل تجربه‌های تازه‌ای یا چیزهای مطمئن؟",
                "یک روز ایده‌آل برای تو چه شکلیه؟",
                "چه ویژگی‌ای در آدم‌ها باعث می‌شه از اول احساس راحتی کنی؟"
            )
            else -> listOf(
                "جالبه که گفتی «$clipped» 😊 چی باعث شد به این موضوع فکر کنی؟",
                "می‌فهمم چی می‌گی. جذاب‌ترین قسمت این ماجرا به نظرت چیه؟",
                "این موضوع چند جنبه‌ی جالب داره! خودت کدوم بخشش برات مهم‌تره؟",
                "راستی بین $otherInterest و $secondInterest کدوم رو بیشتر ترجیح می‌دی؟",
                "یک چیز کوچیک که همیشه حالت رو خوب می‌کنه چیه؟"
            )
        }
        return replies[replyTurn % replies.size]
    }

    fun openingMessage(person: Person): String =
        "سلام! خوشحالم که با هم مچ شدیم 😊 من ${person.name} هستم."
}
