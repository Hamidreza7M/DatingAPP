#!/usr/bin/env python3
"""Write a concise GitHub Actions summary from Gradle/JUnit/JaCoCo outputs."""
from pathlib import Path
import os
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
APP_BUILD = ROOT / "app" / "build"


def junit_totals(patterns):
    totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0, "time": 0.0}
    files = []
    for pattern in patterns:
        files.extend(APP_BUILD.glob(pattern))
    seen = set()
    for file in files:
        if file in seen or not file.is_file():
            continue
        seen.add(file)
        try:
            root = ET.parse(file).getroot()
        except (ET.ParseError, OSError):
            continue
        suites = [root] if root.tag.endswith("testsuite") else list(root.iter("testsuite"))
        for suite in suites:
            totals["tests"] += int(suite.attrib.get("tests", 0))
            totals["failures"] += int(suite.attrib.get("failures", 0))
            totals["errors"] += int(suite.attrib.get("errors", 0))
            totals["skipped"] += int(suite.attrib.get("skipped", 0))
            totals["time"] += float(suite.attrib.get("time", 0.0))
    return totals, len(seen)


def coverage_line():
    report = APP_BUILD / "reports" / "jacoco" / "jacocoTestReport" / "jacocoTestReport.xml"
    if not report.exists():
        native_report = APP_BUILD / "reports" / "coverage" / "test" / "debug" / "index.html"
        if native_report.exists():
            return "JaCoCo HTML generated by Android Gradle Plugin; see uploaded coverage artifact."
        return "Not available (JaCoCo report was not generated)."
    try:
        root = ET.parse(report).getroot()
        line = next((item for item in root.findall("counter") if item.attrib.get("type") == "LINE"), None)
        if line is None:
            return "Not available (LINE counter is missing)."
        covered = int(line.attrib.get("covered", 0))
        missed = int(line.attrib.get("missed", 0))
        total = covered + missed
        pct = (covered / total * 100) if total else 0.0
        return f"{pct:.1f}% ({covered}/{total} lines)"
    except (ET.ParseError, OSError, ValueError):
        return "Could not parse JaCoCo XML."


unit, unit_files = junit_totals(["test-results/testDebugUnitTest/TEST-*.xml"])
instrumented, instrumented_files = junit_totals([
    "outputs/androidTest-results/connected/**/TEST-*.xml",
    "outputs/androidTest-results/connected/TEST-*.xml",
])
android_coverage_report = APP_BUILD / "reports" / "coverage" / "androidTest" / "debug" / "connected" / "index.html"
android_coverage_status = "Generated" if android_coverage_report.exists() else "Not available"
summary = [
    "## FastLove Android CI report",
    "",
    "| Suite | Tests | Failures | Errors | Skipped | Time |",
    "|---|---:|---:|---:|---:|---:|",
    f"| JVM unit tests | {unit['tests']} | {unit['failures']} | {unit['errors']} | {unit['skipped']} | {unit['time']:.1f}s |",
    f"| Instrumented UI tests | {instrumented['tests']} | {instrumented['failures']} | {instrumented['errors']} | {instrumented['skipped']} | {instrumented['time']:.1f}s |",
    "",
    f"**Unit-test line coverage:** {coverage_line()}",
    f"**Instrumented-test coverage:** {android_coverage_status}",
    "",
    f"**JUnit XML files:** {unit_files + instrumented_files}",
    "",
    "Reports are attached to this workflow run as `fastlove-android-reports-*`. The debug APK is uploaded separately when all required jobs pass.",
]
content = "\n".join(summary) + "\n"
summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
if summary_path:
    with open(summary_path, "a", encoding="utf-8") as handle:
        handle.write(content)
else:
    print(content)
